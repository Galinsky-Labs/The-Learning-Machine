import {test,expect} from '@playwright/test';
test('Module 7: build a rule, predict, stress-test, revise, compare, fork and export locally',async({page})=>{
 test.setTimeout(60000);
 const posts=[];page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))posts.push(r.url())});
 await page.goto('/studio');await expect(page.locator('[data-hydrated="true"]')).toBeVisible();
 const picker=page.getByRole('group',{name:'Add term to Rule 1'});
 await picker.getByLabel('Fact').selectOption('access.lawful');await picker.getByLabel('Value').selectOption('true');
 await picker.getByRole('button',{name:'Add term to Rule 1'}).click();
 await expect(page.getByText('If access.lawful is true, then permit.')).toBeVisible();
 await page.getByRole('button',{name:'Submit first draft'}).click();
 await page.getByRole('button',{name:'Commit outcome predictions'}).click();
 await page.getByRole('button',{name:'Run the stress test'}).click();
 await expect(page.getByRole('region',{name:'Stress-test findings'})).toContainText('permits-distributed-copied-expression');
 const carve=page.getByRole('group',{name:'Add carve-out to Rule 1'});
 await carve.getByLabel('Fact').selectOption('outputs.containsProtectedExpression');await carve.getByLabel('Value').selectOption('true');await carve.getByLabel('Then').selectOption('restrict');
 await carve.getByRole('button',{name:'Add carve-out to Rule 1'}).click();
 await page.getByLabel('Comparison scenario').selectOption('regurgitating-output');
 await expect(page.getByText(/Changing rule-1 moved the outcome from permit to restrict/)).toBeVisible();
 await page.getByRole('combobox',{name:'Stress-test finding'}).selectOption('permits-distributed-copied-expression');
 await page.getByLabel(/Save the builder's current draft/).check();
 await page.getByLabel('Why?').fill('Copied, distributed output is not learning, so I carve it out.');
 await page.getByRole('button',{name:'Record response'}).click();
 await page.getByLabel('Your statement').fill('I support learning from lawful copies but not distributing copied expression.');
 await page.getByRole('button',{name:'Finish the module'}).click();
 await expect(page.getByRole('status').filter({hasText:'Module complete with 2 saved revision'})).toBeVisible();
 await page.getByRole('button',{name:'Fork the first draft with the current builder'}).click();
 await page.getByRole('button',{name:'Export history as text'}).click();
 await page.getByRole('button',{name:'Verify imported history'}).click();
 await expect(page.getByText(/Imported 3 revisions; all evidence replays/)).toBeVisible();
 await expect(page.getByText(/not a morality, compliance or quality score/)).toBeVisible();
 expect(posts).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)).toBe(false);
});
test('Module 8: any position completes with reasoning; bare endorsement does not',async({page})=>{
 await page.goto('/capstone');await expect(page.locator('[data-hydrated="true"]')).toBeVisible();
 await page.getByLabel('restrict',{exact:true}).check();
 await page.getByRole('button',{name:'Check my reasoning'}).click();
 await expect(page.getByRole('status').filter({hasText:'Not complete yet'})).toBeVisible();
 await page.getByLabel(/memorizer kept exact copies/).check();
 await page.getByLabel(/permanent library is a separate use/).check();
 await page.getByLabel('How does the evidence apply here?').fill('Because the memorizer kept copies, a guide model could quote scans; whether that matters depends on outputs, which are unknown until tested.');
 await page.getByLabel('The strongest argument against your position').fill('Museums serve the public and guides rarely substitute for art.');
 await page.getByLabel('Your response to it').fill('Agreed for most works, but if guides quoted catalogue essays the market harm might be real.');
 await page.getByRole('button',{name:'Check my reasoning'}).click();
 await expect(page.getByRole('status').filter({hasText:'Capstone complete'})).toBeVisible();
});
